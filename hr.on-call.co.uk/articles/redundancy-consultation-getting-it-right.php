            <p>Making someone redundant is never easy, and it is one of the areas where we see employers making the most mistakes. Even when the business case for redundancy is clear, a flawed process can result in an unfair dismissal claim, and the cost of getting it wrong can be significant.</p>

            <p>In this guide, we will walk you through the redundancy consultation process step by step, so you can handle it with confidence and treat your people fairly along the way.</p>

            <h2>What Counts as a Genuine Redundancy?</h2>

            <p>Before you begin, you need to make sure the situation is actually a redundancy. Under UK law, redundancy arises when:</p>

            <ul>
                <li>The business is closing down entirely</li>
                <li>The workplace where the employee works is closing</li>
                <li>The need for employees to carry out work of a particular kind has ceased or diminished, or is expected to</li>
            </ul>

            <p>If you are simply unhappy with someone's performance or want to replace them with someone different, that is not a redundancy. Using redundancy as a way to remove a specific person is one of the fastest routes to an employment tribunal, and tribunals are well practiced at identifying sham redundancies.</p>

            <h2>Step 1: Plan Before You Act</h2>

            <p>Before you speak to anyone, take time to plan the process properly. You should be clear on:</p>

            <ol>
                <li><strong>The business rationale:</strong> Why is the redundancy necessary? What has changed? Document the commercial reasons clearly.</li>
                <li><strong>Which roles are at risk:</strong> Identify the roles, not the people. Redundancy is about the role becoming unnecessary, not about the individual.</li>
                <li><strong>The selection pool:</strong> If more than one person does the same or similar work, you need to identify a pool of employees from which the redundant individual will be selected. The pool must be defined fairly and logically.</li>
                <li><strong>Selection criteria:</strong> If you have a pool, you need objective criteria to decide who will be selected. Common criteria include skills and qualifications, performance records, attendance and disciplinary records, and length of service. The criteria must be measurable and applied consistently.</li>
                <li><strong>Timeline:</strong> Map out the key dates for the consultation process, selection, and notice periods.</li>
            </ol>

            <h2>Step 2: Start the Consultation Process</h2>

            <p>Consultation is not optional. It is a legal requirement, and skipping it or treating it as a formality is one of the most common mistakes employers make.</p>

            <h3>Individual consultation</h3>

            <p>For all redundancies, you must consult individually with each affected employee. This means having genuine, meaningful discussions about:</p>

            <ul>
                <li>The reasons for the proposed redundancy</li>
                <li>Ways to avoid the redundancy, such as redeployment to another role, reduced hours, or voluntary redundancy</li>
                <li>The selection criteria and how they have been applied (if relevant)</li>
                <li>Any ideas or suggestions the employee has</li>
            </ul>

            <p>The word "meaningful" is critical here. Consultation must take place while the decision is still provisional. If you have already made up your mind before the first meeting, the consultation is a sham and will not protect you at tribunal.</p>

            <p>We recommend holding at least two individual consultation meetings, with a reasonable gap between them to allow the employee to consider the information and respond.</p>

            <h3>Collective consultation</h3>

            <p>If you are proposing to make 20 or more employees redundant within a 90-day period at one establishment, you have additional obligations. You must consult with appropriate employee representatives and notify the Redundancy Payments Service by filing an HR1 form. Collective consultation must begin at least 30 days before the first dismissal takes effect, or 45 days if 100 or more redundancies are proposed.</p>

            <p>Failure to comply with collective consultation requirements can result in a protective award of up to 90 days' pay per affected employee.</p>

            <h2>Step 3: Consider Alternatives to Redundancy</h2>

            <p>During consultation, you must genuinely consider whether there are alternatives to redundancy. This is not just a nice thing to do; it is a legal requirement. Alternatives might include:</p>

            <ul>
                <li>Redeployment to a suitable alternative role within the business</li>
                <li>Reducing overtime or hours across the team</li>
                <li>Offering voluntary redundancy</li>
                <li>Retraining employees for different roles</li>
                <li>Temporary layoffs or short-time working (if contractually permitted)</li>
            </ul>

            <p>If a suitable alternative role exists and you fail to offer it, the dismissal is likely to be unfair. You should actively search for alternative roles throughout the notice period, not just at the start of the process.</p>

            <h2>Step 4: Confirm the Redundancy and Give Notice</h2>

            <p>If, after genuine consultation, redundancy remains necessary, you should confirm the decision in writing. The confirmation letter should include:</p>

            <ol>
                <li>The reason for the redundancy</li>
                <li>A summary of the consultation process and alternatives considered</li>
                <li>The employee's notice period and their last day of employment</li>
                <li>Details of their redundancy pay entitlement</li>
                <li>Any other payments due, such as accrued holiday pay and pay in lieu of notice if applicable</li>
                <li>Their right to appeal the decision</li>
                <li>Their right to reasonable time off to look for a new job (employees with two or more years' service are entitled to this)</li>
            </ol>

            <p>The statutory notice period depends on the employee's length of continuous service: one week for each complete year of service, up to a maximum of 12 weeks, with a minimum of one week for anyone employed for at least one month. Check the employment contract as it may provide for a longer notice period.</p>

            <h2>Redundancy Pay: What You Owe</h2>

            <p>Employees with at least two years' continuous service are entitled to statutory redundancy pay, calculated based on their age, length of service, and weekly pay (subject to a statutory cap which changes annually). The formula is:</p>

            <ul>
                <li>Half a week's pay for each complete year of service where the employee was under 22</li>
                <li>One week's pay for each complete year of service where the employee was aged 22 to 40</li>
                <li>One and a half weeks' pay for each complete year of service where the employee was 41 or over</li>
            </ul>

            <p>Service is capped at 20 years. Some employers choose to offer enhanced redundancy packages above the statutory minimum, particularly where they want to maintain goodwill or are concerned about potential claims. If you are considering a <a href="/documents.php">settlement agreement</a> as an alternative, we can help you weigh up the options.</p>

            <h2>Common Mistakes to Avoid</h2>

            <p>Here are the most frequent errors we see when advising employers on redundancies:</p>

            <ul>
                <li><strong>Targeting a specific individual:</strong> If the real reason is performance or personality, use the appropriate process instead.</li>
                <li><strong>Rushing the consultation:</strong> There is no minimum period for individual consultation, but one meeting followed by a dismissal letter the next day will look very thin at tribunal.</li>
                <li><strong>Using subjective selection criteria:</strong> Criteria like "attitude" or "cultural fit" are difficult to measure objectively and are easy to challenge.</li>
                <li><strong>Forgetting to look for alternative roles:</strong> This needs to be an ongoing obligation, not a one-off check.</li>
                <li><strong>Not offering the right to appeal:</strong> Just like any other dismissal, the employee should have the right to <a href="/articles/disciplinary-and-grievance-appeals.php">appeal the decision</a>.</li>
            </ul>

