            <p>If you have received a complaint from an employee, or you suspect that something has gone wrong in your workplace, you may need to carry out a formal investigation. For many business owners, this is unfamiliar territory and it can feel overwhelming. The good news is that with the right approach, you can run a fair and thorough investigation, even if you have never done one before.</p>

            <p>In this guide, we will walk you through each stage of the process so you know exactly what to do, and just as importantly, what to avoid.</p>

            <h2>Why Workplace Investigations Matter</h2>

            <p>A workplace investigation is the fact-finding stage that takes place before any formal action, such as a <a href="/workplace-issues.php#disciplinary">disciplinary hearing</a>. Its purpose is to establish what happened, gather evidence, and decide whether there is a case to answer.</p>

            <p>Getting this stage right is essential. If you skip the investigation or rush through it, any disciplinary action you take afterwards could be found to be unfair at an employment tribunal. The ACAS Code of Practice makes it clear that employers should carry out a reasonable investigation before taking formal action.</p>

            <p>An investigation is not about finding someone guilty. It is about gathering facts so that a fair decision can be made later.</p>

            <h2>Step 1: Plan the Investigation</h2>

            <p>Before you start speaking to anyone, take the time to plan. Good preparation makes the rest of the process much smoother.</p>

            <ol>
                <li><strong>Identify the allegation or concern.</strong> Write down clearly what is being investigated. Be specific. For example, rather than writing "bullying", write "an allegation that Employee A made repeated derogatory comments to Employee B during team meetings in January and February 2026."</li>
                <li><strong>Appoint an investigation officer.</strong> This should be someone who is impartial and has had no prior involvement in the matter. In small businesses where this is difficult, consider bringing in an <a href="/workplace-issues.php#investigations">external investigator</a>.</li>
                <li><strong>Set a terms of reference.</strong> This is a short document that outlines what the investigation will cover, who will carry it out, and the expected timeframe. It keeps the investigation focused.</li>
                <li><strong>Consider suspension.</strong> If the allegation is serious, such as gross misconduct, you may need to suspend the employee on full pay while the investigation takes place. Suspension should only be used where genuinely necessary, for example to prevent interference with evidence or to protect other employees.</li>
            </ol>

            <h2>Step 2: Gather Evidence</h2>

            <p>Evidence can come in many forms. Think broadly about what might be relevant:</p>

            <ul>
                <li>Emails, messages, or other written communications</li>
                <li>CCTV footage</li>
                <li>Computer or system records</li>
                <li>Attendance or timekeeping records</li>
                <li>Witness accounts</li>
                <li>Company policies and procedures</li>
                <li>Previous warnings or relevant correspondence</li>
            </ul>

            <p>Collect and secure any documentary evidence early. If there is CCTV footage or electronic records, make sure these are preserved before they are automatically overwritten.</p>

            <h2>Step 3: Conduct Investigation Interviews</h2>

            <p>Interviews are usually the most important part of any workplace investigation. Here is how to approach them:</p>

            <ol>
                <li><strong>Interview the complainant first</strong> (if there is one). Understand their account in full before speaking to others.</li>
                <li><strong>Interview witnesses.</strong> Speak to anyone who may have relevant information. Ask open questions like "What did you see?" rather than leading questions like "You saw him do it, didn't you?"</li>
                <li><strong>Interview the person under investigation.</strong> They must be given the opportunity to respond to the allegations. Let them know what is being investigated and give them a chance to put forward their side of the story.</li>
                <li><strong>Take detailed notes.</strong> Record who said what, including the date, time and who was present. Ask the interviewee to review and sign the notes where possible.</li>
                <li><strong>Allow the right to be accompanied.</strong> Employees have the right to be accompanied by a trade union representative or a work colleague at formal investigation meetings.</li>
            </ol>

            <p>Stay neutral throughout. Your role at this stage is to listen and gather information, not to form conclusions mid-interview.</p>

            <h2>Step 4: Analyse Findings and Write the Report</h2>

            <p>Once all the evidence has been gathered and interviews completed, the investigation officer should write a report. This does not need to be a lengthy legal document. It should include:</p>

            <ul>
                <li>A summary of the allegation or concern</li>
                <li>The evidence gathered, including interview summaries</li>
                <li>The findings of fact, i.e. what the investigator believes happened based on the balance of probabilities</li>
                <li>A recommendation on whether there is a case to answer</li>
            </ul>

            <p>The investigation report is then passed to a separate decision-maker, who will decide whether to proceed to a <a href="/articles/how-to-handle-a-disciplinary-hearing.php">disciplinary hearing</a> or take other action.</p>

            <h2>Common Mistakes to Avoid</h2>

            <p>Having supported many employers through this process at HR On Call, we see the same mistakes come up repeatedly. Here are the most common ones:</p>

            <ul>
                <li><strong>Jumping to conclusions.</strong> Do not assume guilt before the investigation is complete. Keep an open mind throughout.</li>
                <li><strong>Failing to investigate at all.</strong> Some employers skip straight to a disciplinary hearing. This is one of the quickest ways to lose a tribunal claim.</li>
                <li><strong>Using the wrong person as investigator.</strong> The person who investigates must not be the same person who chairs any subsequent hearing. They need to be separate roles.</li>
                <li><strong>Taking too long.</strong> Investigations should be carried out without unreasonable delay. Keep the employee informed of progress.</li>
                <li><strong>Not keeping records.</strong> If it is not written down, it did not happen, at least as far as a tribunal is concerned.</li>
            </ul>

