            <p>If you employ people in the UK, you will almost certainly have come across references to the ACAS Code of Practice. It gets mentioned in almost every conversation about disciplinary procedures, grievances and dismissals. But what actually is it, and what happens if you do not follow it?</p>

            <p>In this guide, we will explain the ACAS Code in straightforward terms, cover the key requirements it sets out, and show you how to make sure your business stays on the right side of it.</p>

            <h2>What Is the ACAS Code of Practice?</h2>

            <p>ACAS stands for the Advisory, Conciliation and Arbitration Service. It is a publicly funded body that provides guidance on workplace relations in the UK. The ACAS Code of Practice on Disciplinary and Grievance Procedures is a set of practical guidelines that outlines the minimum standards employers should follow when dealing with disciplinary and grievance situations.</p>

            <p>It is important to understand that the Code is not legislation in the same way as the Employment Rights Act. However, employment tribunals are required by law to take it into account when considering relevant cases. If you have failed to follow the Code without good reason, a tribunal can increase any compensation award by up to 25 percent. Equally, if an employee has unreasonably failed to follow the Code, any award can be reduced by up to 25 percent.</p>

            <p>In practical terms, this means that following the ACAS Code is not optional if you want to protect your business.</p>

            <h2>The Key Principles of the ACAS Code</h2>

            <p>The Code sets out several fundamental principles that should underpin your approach to any disciplinary or grievance matter. These are:</p>

            <ul>
                <li><strong>Act promptly.</strong> Do not let issues drag on. Deal with matters without unreasonable delay.</li>
                <li><strong>Be consistent.</strong> Apply your policies and procedures evenly across all employees. Treating similar situations differently creates unfairness and legal risk.</li>
                <li><strong>Investigate thoroughly.</strong> Before taking any formal action, carry out a <a href="/articles/how-to-conduct-a-workplace-investigation.php">reasonable investigation</a> to establish the facts.</li>
                <li><strong>Inform the employee.</strong> The employee must be told in writing what the issue is, along with enough detail to allow them to prepare their response.</li>
                <li><strong>Hold a meeting.</strong> Give the employee the opportunity to put their case at a formal meeting before any decision is made.</li>
                <li><strong>Allow the right to be accompanied.</strong> Employees have a statutory right to be accompanied by a trade union representative or a work colleague at any formal disciplinary or grievance meeting.</li>
                <li><strong>Provide the right of appeal.</strong> After any formal outcome, the employee must be given the opportunity to appeal.</li>
            </ul>

            <h2>What the Code Says About Disciplinary Procedures</h2>

            <p>When dealing with a disciplinary matter, the Code expects employers to follow these steps:</p>

            <ol>
                <li><strong>Establish the facts.</strong> Carry out an investigation before taking any formal action. This might mean gathering documents, speaking to witnesses and reviewing relevant policies.</li>
                <li><strong>Notify the employee in writing.</strong> Send a letter setting out the allegations, the evidence you are relying on, and the details of the <a href="/articles/how-to-handle-a-disciplinary-hearing.php">disciplinary hearing</a>. Give the employee enough time to prepare.</li>
                <li><strong>Hold the hearing.</strong> At the hearing, present the management case and allow the employee to respond. They should be able to ask questions, call witnesses, and put forward any mitigating circumstances.</li>
                <li><strong>Decide on the outcome.</strong> After the hearing, take time to consider everything before making a decision. Possible outcomes include no further action, a written warning, a final written warning, or dismissal.</li>
                <li><strong>Confirm the outcome in writing.</strong> Set out the decision, the reasons for it, and the right of appeal.</li>
                <li><strong>Offer an appeal.</strong> If the employee disagrees with the outcome, they should be able to appeal to a more senior manager or someone who has not been involved in the process.</li>
            </ol>

            <h2>What the Code Says About Grievance Procedures</h2>

            <p>A grievance is a complaint raised by an employee about something in the workplace, whether that is how they have been treated, a decision that has been made, or the behaviour of a colleague. The Code expects employers to handle grievances as follows:</p>

            <ol>
                <li><strong>Let the employee raise the grievance formally.</strong> They should put their complaint in writing to their employer.</li>
                <li><strong>Arrange a meeting.</strong> Hold a <a href="/articles/how-to-handle-a-grievance-at-work.php">grievance meeting</a> to discuss the complaint. This should happen without unreasonable delay.</li>
                <li><strong>Investigate as necessary.</strong> Depending on the nature of the complaint, you may need to carry out a separate investigation before or after the meeting.</li>
                <li><strong>Communicate the outcome.</strong> Write to the employee with your decision and the reasons behind it.</li>
                <li><strong>Allow an appeal.</strong> If the employee is not satisfied with the outcome, they should be able to appeal.</li>
            </ol>

            <h2>Practical Tips for Staying Compliant</h2>

            <p>Over the years working with employers at HR On Call, we have found that the most common reason businesses fall foul of the ACAS Code is not because they are acting in bad faith, but because they simply do not know the correct procedure. Here are some practical steps you can take:</p>

            <ul>
                <li><strong>Have a written disciplinary and grievance policy.</strong> Make sure it reflects the ACAS Code and that all employees have access to it. If you need one, we can help you put together the right <a href="/documents.php">HR documentation</a>.</li>
                <li><strong>Train your managers.</strong> Anyone who might need to handle a disciplinary or grievance situation should understand the basics of the process.</li>
                <li><strong>Keep records.</strong> Document every step of the process, from the initial complaint through to the outcome and any appeal. Good records are your best protection if a claim is brought.</li>
                <li><strong>Use separate people for each stage.</strong> Where possible, the person who investigates should not be the same person who chairs the hearing, and the appeal should be heard by someone different again.</li>
                <li><strong>Seek advice early.</strong> If you are unsure about any part of the process, getting professional guidance at the start is far cheaper and less stressful than trying to fix things after a tribunal claim has been lodged.</li>
            </ul>

            <p>The ACAS Code is there to ensure fairness for both employers and employees. By following it, you are not just protecting your business from legal claims but also creating a workplace where issues are dealt with properly and people are treated with respect.</p>

