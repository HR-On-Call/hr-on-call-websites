            <p>Settlement agreements are one of the most useful tools available to UK employers. When used at the right time, they allow you to bring an employment relationship to a clean end, with both sides walking away knowing exactly where they stand. But if you have never dealt with one before, the process can seem complicated and expensive.</p>

            <p>In this guide, we will explain what settlement agreements are, when you should consider using one, and how the process works in practice.</p>

            <h2>What Is a Settlement Agreement?</h2>

            <p>A settlement agreement is a legally binding contract between an employer and an employee. The employee agrees to waive their right to bring certain employment tribunal claims in exchange for something, usually a financial payment. You may also hear them referred to by their old name, compromise agreements, but the legal effect is the same.</p>

            <p>For a settlement agreement to be legally valid, three conditions must be met:</p>

            <ol>
                <li>It must be in writing</li>
                <li>The employee must have received independent legal advice on the terms and effect of the agreement</li>
                <li>The legal adviser must be identified in the agreement and must have a current insurance policy covering the advice</li>
            </ol>

            <p>This means that unlike a simple resignation, a settlement agreement gives you genuine protection against future claims. That peace of mind is often worth the cost involved.</p>

            <h2>When Should You Consider a Settlement Agreement?</h2>

            <p>There are a number of situations where a settlement agreement might be the right approach. Here are the most common ones we encounter:</p>

            <ul>
                <li><strong>Long-running performance issues:</strong> When you have been managing poor performance for months and the situation is not improving, a settlement agreement can provide a dignified exit for both parties.</li>
                <li><strong>Relationship breakdown:</strong> Sometimes the working relationship has simply broken down beyond repair, even if no one is at fault.</li>
                <li><strong>Redundancy situations:</strong> Settlement agreements can be used alongside or instead of a formal <a href="/workplace-issues.php">redundancy process</a>, particularly where there is only one role at risk.</li>
                <li><strong>Grievance or disciplinary situations:</strong> Where a grievance or disciplinary matter has become complex and both sides would benefit from drawing a line under things.</li>
                <li><strong>Protecting confidential information:</strong> Settlement agreements can include confidentiality clauses that go beyond what you can normally enforce.</li>
            </ul>

            <h2>How Much Does a Settlement Agreement Cost?</h2>

            <p>There are two main costs to factor in when considering a settlement agreement:</p>

            <h3>The settlement payment</h3>

            <p>There is no fixed formula for calculating the payment. The amount will depend on the circumstances, including the employee's length of service, salary, the strength of any potential claims, and what you are trying to achieve. As a very rough starting point, many employers begin discussions at around one to three months' salary, but this varies enormously.</p>

            <p>The first portion of any termination payment, up to a statutory threshold, can usually be paid free of tax and National Insurance, provided it is genuinely compensatory and not simply disguised wages. Your accountant or solicitor can advise on the tax treatment for your specific situation.</p>

            <h3>Legal fees contribution</h3>

            <p>Because the employee must take independent legal advice, it is standard practice for the employer to make a contribution towards those costs. This typically ranges from around 350 to 500 pounds plus VAT, though it can be higher for more complex agreements. This is a cost you should expect to pay regardless of the settlement amount.</p>

            <h2>The Settlement Agreement Process: Step by Step</h2>

            <p>Here is how the process typically works in practice:</p>

            <ol>
                <li><strong>Have a protected conversation:</strong> You can have an off-the-record discussion with the employee about the possibility of a settlement agreement. Under section 111A of the Employment Rights Act 1996, pre-termination negotiations are generally inadmissible at tribunal, provided there is no improper behaviour. This means you can speak openly without worrying that the conversation will be used against you.</li>
                <li><strong>Put together the offer:</strong> If the employee is receptive, set out your proposed terms. we recommend putting the headline terms in a brief letter before sending the full legal document, so both sides are clear on what is being proposed.</li>
                <li><strong>Instruct a solicitor to draft the agreement:</strong> The agreement itself should be drafted or reviewed by a solicitor. If you do not have one, this is something we can help coordinate through HR On Call's <a href="/documents.php">document support service</a>.</li>
                <li><strong>Send the agreement to the employee:</strong> Give the employee a reasonable amount of time to consider the terms and take legal advice. ACAS recommends a minimum of ten calendar days, though this can be shorter if both parties agree.</li>
                <li><strong>Employee takes legal advice:</strong> The employee's solicitor will review the agreement and may come back with questions or requests for changes. A degree of negotiation at this stage is normal.</li>
                <li><strong>Both parties sign:</strong> Once both sides are happy with the terms, the agreement is signed. The employee's solicitor provides a certificate confirming they have given independent legal advice.</li>
                <li><strong>Payment and departure:</strong> You make the agreed payment and the employee leaves on the terms set out in the agreement.</li>
            </ol>

            <h2>Key Clauses to Include</h2>

            <p>While your solicitor will handle the detailed drafting, it is helpful to understand the key clauses that most settlement agreements contain:</p>

            <ul>
                <li><strong>Termination date:</strong> The date the employment will end, or has ended.</li>
                <li><strong>Payment terms:</strong> The amount, tax treatment, and payment date.</li>
                <li><strong>Waiver of claims:</strong> A list of the specific claims the employee is agreeing not to bring.</li>
                <li><strong>Confidentiality:</strong> An obligation on both parties not to disclose the terms of the agreement.</li>
                <li><strong>Reference:</strong> An agreed form of reference that you will provide to future employers.</li>
                <li><strong>Return of property:</strong> Arrangements for returning company equipment, documents, and data.</li>
                <li><strong>Post-termination restrictions:</strong> Any restrictive covenants you want to include or carry over from the employment contract.</li>
            </ul>

            <h2>Common Mistakes Employers Make</h2>

            <p>Based on our experience advising employers, here are the most frequent pitfalls:</p>

            <ul>
                <li><strong>Springing it on the employee:</strong> A settlement agreement should feel like a genuine offer, not a threat. Handle the initial conversation sensitively.</li>
                <li><strong>Not allowing enough time:</strong> Pressuring an employee to sign quickly can make the agreement unenforceable and creates a poor impression.</li>
                <li><strong>Forgetting about outstanding entitlements:</strong> Make sure you account for accrued holiday, notice pay, bonus entitlements, and any other contractual payments.</li>
                <li><strong>Using a generic template:</strong> Every situation is different. The agreement needs to be tailored to the specific circumstances and the claims you are trying to settle.</li>
                <li><strong>Not getting your own advice:</strong> Just because the employee needs a solicitor does not mean you do not. Having proper <a href="/retainers.php">HR support</a> throughout the process helps you avoid costly errors.</li>
            </ul>

