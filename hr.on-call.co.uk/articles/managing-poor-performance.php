            <p>Dealing with an employee who is not performing well is one of the most difficult challenges you will face as an employer. It is uncomfortable, it takes time, and if you get it wrong, it can lead to an unfair dismissal claim. But ignoring the problem is not an option either, because poor performance left unchecked affects your whole team.</p>

            <p>In this guide, we will take you through the process of managing poor performance step by step, from the initial conversation through to formal action if things do not improve.</p>

            <h2>Performance vs Conduct: Why the Distinction Matters</h2>

            <p>Before you start, it is important to understand the difference between poor performance and misconduct. They require different approaches:</p>

            <ul>
                <li><strong>Poor performance (capability):</strong> The employee is trying but is not meeting the required standard. This might be due to lack of skill, inadequate training, personal issues, or simply being in the wrong role.</li>
                <li><strong>Misconduct:</strong> The employee is choosing not to follow rules or meet expectations. This includes things like persistent lateness, refusal to follow instructions, or dishonesty.</li>
            </ul>

            <p>If the issue is genuinely about capability rather than conduct, you should follow a capability or performance management procedure rather than a disciplinary one. The ACAS Code of Practice applies to both, but the tone and approach are quite different. A capability process is supportive in nature. You are trying to help the employee improve, not punish them.</p>

            <h2>Step 1: Have an Informal Conversation First</h2>

            <p>In most cases, your first step should be an informal discussion with the employee. This is not a formal meeting, but it does need to be honest and specific. Vague feedback like "you need to do better" is not helpful for anyone.</p>

            <p>During this conversation, you should:</p>

            <ol>
                <li>Explain clearly what the expected standard is and where they are falling short, using specific examples</li>
                <li>Ask if there is anything affecting their ability to do the job, such as health problems, personal issues, or lack of training</li>
                <li>Agree on what improvement looks like and by when</li>
                <li>Offer any support that might help, such as additional training, mentoring, or adjusted workload</li>
                <li>Make a note of the conversation and follow up in writing so everyone is clear on what was discussed</li>
            </ol>

            <p>Many performance issues can be resolved at this stage. Give the employee a reasonable amount of time to improve. What counts as reasonable will depend on the role and the nature of the shortfall, but two to four weeks is often a sensible starting point.</p>

            <h2>Step 2: Implement a Performance Improvement Plan</h2>

            <p>If the informal approach does not work, the next step is usually a Performance Improvement Plan, commonly known as a PIP. This is a structured document that sets out exactly what is expected and gives the employee a clear framework for improvement.</p>

            <p>A good PIP should include:</p>

            <ul>
                <li><strong>Specific objectives:</strong> What does the employee need to achieve? Use measurable targets wherever possible.</li>
                <li><strong>A realistic timeframe:</strong> Typically four to twelve weeks depending on the complexity of the role. Setting too short a timeframe can make the process look like a box-ticking exercise.</li>
                <li><strong>Support offered:</strong> What will you provide to help the employee succeed? This might include training, regular check-ins, adjusted duties, or mentoring.</li>
                <li><strong>Review dates:</strong> Schedule regular progress meetings, usually weekly or fortnightly, so both sides know how things are going.</li>
                <li><strong>Consequences of not improving:</strong> Be clear that if the required standards are not met, the matter may progress to a formal capability hearing.</li>
            </ul>

            <p>It is important that the PIP is genuinely designed to help the employee improve, not simply to build a paper trail for dismissal. Tribunals are very good at spotting the difference, and if your PIP sets unrealistic targets or provides no meaningful support, it will not protect you.</p>

            <h2>Step 3: Move to Formal Capability Proceedings if Needed</h2>

            <p>If the employee has not improved sufficiently despite the PIP and the support you have provided, you may need to move to formal capability proceedings. This is where the process becomes similar to a disciplinary procedure, and you must follow the ACAS Code of Practice carefully.</p>

            <p>The formal process involves:</p>

            <ol>
                <li><strong>Write to the employee:</strong> Invite them to a formal capability meeting. Set out the concerns in enough detail for them to understand and prepare a response. Give at least five working days' notice.</li>
                <li><strong>Inform them of their rights:</strong> They have the right to be accompanied by a trade union representative or a work colleague.</li>
                <li><strong>Hold the meeting:</strong> Present the evidence of underperformance, including the PIP outcomes and review notes. Give the employee a full opportunity to respond and put forward any mitigating factors.</li>
                <li><strong>Make a decision:</strong> After the meeting, decide on the appropriate outcome. Options typically include issuing a formal warning with a further review period, issuing a final written warning, or in serious cases, dismissal with notice.</li>
                <li><strong>Confirm in writing:</strong> Write to the employee with your decision, the reasons for it, and their right to appeal.</li>
            </ol>

            <h2>How to Handle the Escalation Fairly</h2>

            <p>If you do need to escalate through warnings to potential dismissal, make sure you can demonstrate that at each stage you have:</p>

            <ul>
                <li>Been clear about the standards required</li>
                <li>Given the employee a genuine opportunity to improve</li>
                <li>Provided appropriate support and training</li>
                <li>Allowed reasonable time for improvement</li>
                <li>Considered any reasons or explanations the employee has offered</li>
                <li>Followed your own policies and the ACAS Code</li>
            </ul>

            <p>If you can show all of this, you will be in a strong position should the matter ever reach a tribunal. The key test is whether dismissal fell within the range of reasonable responses open to a reasonable employer.</p>

            <h2>Practical Tips From Our Experience</h2>

            <p>Having supported many employers through performance management processes, here are a few things we always recommend:</p>

            <ul>
                <li><strong>Document everything:</strong> Keep notes of all conversations, meetings, and reviews. If it is not written down, it did not happen.</li>
                <li><strong>Be consistent:</strong> Apply the same standards and processes to everyone. Treating one employee differently from another in similar circumstances is a fast track to a discrimination claim.</li>
                <li><strong>Do not delay:</strong> The longer you leave a performance issue, the harder it is to address. Early intervention is always better.</li>
                <li><strong>Consider the whole picture:</strong> Sometimes poor performance is a symptom of something else, such as a health condition, workplace difficulties, or problems at home. A compassionate approach is not just the right thing to do, it is also what the law expects.</li>
                <li><strong>Get advice early:</strong> If you are unsure at any stage, it is far better to seek <a href="/retainers.php">ongoing HR support</a> before you act than to try to fix a flawed process afterwards.</li>
            </ul>

            <p>Managing poor performance well takes time and patience, but it is one of the most important skills you can develop as an employer. Done properly, it protects your business, supports your team, and gives the employee a fair chance to succeed.</p>

