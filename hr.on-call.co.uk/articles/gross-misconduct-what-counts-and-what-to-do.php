            <p>When something serious happens in your workplace, such as theft, violence, or fraud, your instinct might be to dismiss the employee immediately. And in many cases, you would be right to consider it. But even in the most clear-cut situations, there is a process you must follow. Getting it wrong can turn a strong position into an expensive unfair dismissal claim.</p>

            <p>In this guide, we will explain what gross misconduct actually means, give you practical examples, and walk you through the correct process for handling it.</p>

            <h2>What Is Gross Misconduct?</h2>

            <p>Gross misconduct is behaviour so serious that it fundamentally breaks the trust and confidence between employer and employee. It is the type of conduct that entitles an employer to dismiss the employee without notice, known as summary dismissal.</p>

            <p>Ordinary misconduct, such as occasional lateness or a minor breach of a workplace rule, would normally be dealt with through warnings. Gross misconduct is in a different category. It is behaviour that goes to the heart of the employment relationship and makes it unreasonable to expect the employer to continue employing that person.</p>

            <p>It is important that your employment contracts and staff handbook include a list of what your business considers to be gross misconduct. While there is no definitive legal list, having your own examples set out in writing makes things much clearer if a situation arises.</p>

            <h2>Common Examples of Gross Misconduct</h2>

            <p>While every situation must be judged on its own facts, the following are widely recognised as examples of conduct that may constitute gross misconduct:</p>

            <ul>
                <li><strong>Theft or fraud.</strong> This includes stealing from the employer, colleagues, or customers, as well as falsifying expenses, timesheets, or other records.</li>
                <li><strong>Physical violence or threats of violence.</strong> Any act of violence in the workplace, or credible threats of violence, is typically regarded as gross misconduct.</li>
                <li><strong>Serious bullying or harassment.</strong> This includes behaviour related to protected characteristics under the Equality Act 2010, as well as other forms of serious bullying.</li>
                <li><strong>Serious health and safety breaches.</strong> Deliberately ignoring safety procedures in a way that puts people at risk.</li>
                <li><strong>Being under the influence of drugs or alcohol at work.</strong> Particularly where this creates a safety risk or makes the employee unable to perform their duties.</li>
                <li><strong>Serious breach of confidentiality.</strong> Sharing sensitive company information, customer data, or trade secrets without authorisation.</li>
                <li><strong>Gross insubordination.</strong> A wilful refusal to follow a reasonable and lawful management instruction.</li>
                <li><strong>Bringing the organisation into serious disrepute.</strong> This could include criminal conduct outside of work that is relevant to the employment, or seriously offensive behaviour on social media.</li>
                <li><strong>Serious negligence.</strong> Causing or risking significant loss or damage through a serious failure to take reasonable care.</li>
            </ul>

            <p>This is not an exhaustive list. What matters is whether the behaviour, in all the circumstances, is serious enough to justify dismissal without notice.</p>

            <h2>The Process You Must Follow</h2>

            <p>Here is where many employers go wrong. Even when the misconduct is obvious, perhaps caught on camera or admitted by the employee, you still need to follow a fair process. Skipping the process is the most common reason employers lose gross misconduct cases at tribunal.</p>

            <p>The <a href="/articles/acas-code-of-practice-what-employers-need-to-know.php">ACAS Code of Practice</a> applies to gross misconduct cases just as it does to any other disciplinary matter. Here is what you should do:</p>

            <ol>
                <li><strong>Suspend the employee.</strong> In gross misconduct cases, it is usually appropriate to suspend the employee on full pay while you investigate. Make clear that suspension is not a punishment and does not imply guilt. Confirm the suspension in writing.</li>
                <li><strong>Investigate.</strong> Carry out a thorough <a href="/articles/how-to-conduct-a-workplace-investigation.php">investigation</a> to establish the facts. Gather evidence, interview witnesses, and give the employee the opportunity to provide their account.</li>
                <li><strong>Hold a disciplinary hearing.</strong> Write to the employee setting out the allegations, providing the evidence, and inviting them to a <a href="/articles/how-to-handle-a-disciplinary-hearing.php">disciplinary hearing</a>. Give them reasonable notice and remind them of their right to be accompanied.</li>
                <li><strong>Consider the employee's response.</strong> At the hearing, listen to what the employee has to say. They may have an explanation, or there may be mitigating circumstances that affect the appropriate sanction.</li>
                <li><strong>Make your decision.</strong> If, having considered everything, you reasonably believe the gross misconduct occurred and that dismissal is a proportionate response, you may proceed with summary dismissal.</li>
                <li><strong>Confirm the outcome in writing.</strong> Your letter should set out the allegation, your findings, the decision to dismiss, the effective date of termination, and the employee's right to appeal.</li>
                <li><strong>Offer an appeal.</strong> The employee must be given the right to appeal the decision. This should be heard by someone who was not involved in the original process.</li>
            </ol>

            <h2>Summary Dismissal: What It Means in Practice</h2>

            <p>Summary dismissal means dismissal without notice. In a gross misconduct case, the employee's contract is terminated immediately. They are not entitled to their notice period or pay in lieu of notice, although they must still receive payment for any accrued but untaken holiday.</p>

            <p>It is worth noting that summary dismissal is only appropriate where the conduct genuinely amounts to gross misconduct. If a tribunal later finds that the behaviour was not serious enough to warrant summary dismissal, the employer could face a claim for wrongful dismissal (for the unpaid notice period) in addition to any unfair dismissal claim.</p>

            <p>This is why it is so important to consider each case on its individual facts rather than having a blanket policy of automatic dismissal for certain offences. Context matters. An employee with 20 years of unblemished service who makes a single error of judgement might warrant a different outcome from someone who has only been with you for six months and has previous warnings.</p>

            <h2>Protecting Your Business</h2>

            <p>The most important thing you can do to protect your business is to follow the process, even when the misconduct seems obvious. Here are some additional tips:</p>

            <ul>
                <li><strong>Keep your policies up to date.</strong> Make sure your <a href="/documents.php">employment contracts</a> and handbook list examples of gross misconduct and set out your disciplinary procedure.</li>
                <li><strong>Act promptly.</strong> Once you become aware of potential gross misconduct, act quickly. Delays can undermine the seriousness of the matter and may be seen as a sign that you did not consider it serious enough to warrant immediate action.</li>
                <li><strong>Document everything.</strong> Keep a written record of every step, from the initial report through to the outcome and appeal.</li>
                <li><strong>Do not skip the investigation.</strong> Even if the employee admits the misconduct, you should still carry out a reasonable investigation and hold a hearing. The process is there to protect you as much as the employee.</li>
                <li><strong>Get advice if you are unsure.</strong> Gross misconduct cases are high stakes. If you are dealing with one for the first time, or the situation is complicated, getting professional HR support can save you from costly mistakes.</li>
            </ul>

