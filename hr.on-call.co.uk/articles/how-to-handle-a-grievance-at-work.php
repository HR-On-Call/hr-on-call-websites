            <p>Receiving a formal grievance from an employee can feel like a personal attack, especially if you are a small business owner who has worked hard to create a good workplace. But a grievance is simply a formal complaint, and how you respond to it matters far more than the fact that it was raised in the first place.</p>

            <p>Handling a grievance properly protects your business, shows your team that concerns are taken seriously, and can often resolve issues before they escalate into something much more costly. In this guide, we will walk you through the process step by step.</p>

            <h2>What Is a Grievance?</h2>

            <p>A grievance is a formal complaint raised by an employee about something related to their work. This could include concerns about how they are being treated by a manager or colleague, disagreements about working conditions or contractual terms, complaints about changes to their role or hours, allegations of bullying, harassment or discrimination, or dissatisfaction with a management decision.</p>

            <p>Employees might try to raise these issues informally first, and wherever possible, resolving things at an early stage is usually best for everyone. But if the issue cannot be resolved informally, or if the matter is serious, the employee has the right to raise a formal grievance.</p>

            <p>The <a href="/articles/acas-code-of-practice-what-employers-need-to-know.php">ACAS Code of Practice</a> sets out the minimum steps employers should follow when handling grievances. Failing to follow the Code can result in a tribunal increasing any compensation by up to 25 percent, so it is important to take grievances seriously from the outset.</p>

            <h2>Step 1: Acknowledge the Grievance</h2>

            <p>When an employee submits a formal grievance, your first step is to acknowledge it in writing. Do this promptly, ideally within two to three working days. Your acknowledgement should confirm that the grievance has been received, outline the next steps in the process, and provide the date and time of the grievance meeting.</p>

            <p>If the grievance letter is vague or unclear, it is perfectly reasonable to ask the employee to clarify their concerns before the meeting. You need to understand what you are being asked to address.</p>

            <p>At this stage, you also need to decide who will hear the grievance. This should be someone with the authority to make decisions and who has not been directly involved in the matters complained about. In small businesses where options are limited, consider whether an <a href="/workplace-issues.php#grievance">external HR professional</a> should handle the process.</p>

            <h2>Step 2: Hold the Grievance Meeting</h2>

            <p>The grievance meeting is the employee's opportunity to explain their complaint in full. Here is how to approach it:</p>

            <ol>
                <li><strong>Prepare in advance.</strong> Read the grievance letter carefully and make a list of questions you want to ask. Think about what documents or records might be relevant.</li>
                <li><strong>Remind the employee of their right to be accompanied.</strong> They can bring a trade union representative or a work colleague to the meeting.</li>
                <li><strong>Listen carefully.</strong> Let the employee talk. Do not interrupt or become defensive, even if you disagree with what is being said. Your role at this point is to understand the complaint fully.</li>
                <li><strong>Ask clarifying questions.</strong> Make sure you understand exactly what the employee is complaining about, when it happened, who was involved, and what outcome they are looking for.</li>
                <li><strong>Take notes.</strong> Have a note-taker present or, if that is not possible, take your own detailed notes. These form an important part of the record.</li>
                <li><strong>Explain what happens next.</strong> At the end of the meeting, tell the employee what the next steps will be and give them an indication of the timeline.</li>
            </ol>

            <p>The tone of the meeting matters. Even if you believe the grievance is unfounded, the employee clearly feels strongly enough to have raised a formal complaint. Treating them with respect throughout the process is not just the right thing to do but it also protects you if the matter ends up at a tribunal.</p>

            <h2>Step 3: Investigate</h2>

            <p>Depending on the nature of the grievance, you may need to carry out an investigation after the meeting. This is particularly important if the grievance involves allegations about another person's behaviour, there are factual disputes that need resolving, or the complaint touches on potential discrimination or harassment.</p>

            <p>The investigation process for a grievance is similar to a <a href="/articles/how-to-conduct-a-workplace-investigation.php">workplace investigation</a> for disciplinary matters. Gather relevant documents, interview witnesses, and consider any other evidence that is available. Keep the employee informed of progress, especially if the investigation is taking longer than expected.</p>

            <p>Not every grievance requires a full investigation. If the complaint is about a management decision and the facts are not in dispute, you may be able to consider the matter based on what was discussed at the grievance meeting alone.</p>

            <h2>Step 4: Decide and Communicate the Outcome</h2>

            <p>Once you have all the information you need, it is time to make a decision. Consider the evidence, the employee's account, and any relevant policies or procedures. Then write to the employee with your decision. The outcome letter should include:</p>

            <ul>
                <li>A summary of the grievance as you understand it</li>
                <li>Your findings on each point raised</li>
                <li>The reasons for your decision</li>
                <li>Any actions you intend to take as a result</li>
                <li>The employee's right to appeal</li>
            </ul>

            <p>Be honest in your response. If the grievance is upheld, say so and explain what you are going to do about it. If it is not upheld, explain clearly why not. If it is partially upheld, set out which aspects you agree with and which you do not.</p>

            <p>Common outcomes of a grievance process include changes to working arrangements, mediation between parties, management training or coaching, a review of relevant policies, an apology where appropriate, or a finding that the grievance is not upheld with reasons given.</p>

            <h2>Step 5: Offer the Right to Appeal</h2>

            <p>The ACAS Code requires that employees are given the right to appeal the grievance outcome. The appeal should be heard by a more senior manager or someone who has not been involved in the process so far.</p>

            <p>Set a reasonable deadline for the employee to submit their appeal, usually five to ten working days from the date of the outcome letter. If an appeal is received, arrange an appeal meeting following the same principles of fairness and thoroughness.</p>

            <h2>Common Pitfalls to Avoid</h2>

            <p>From our experience supporting employers at HR On Call, these are the most frequent mistakes we see:</p>

            <ul>
                <li><strong>Ignoring the grievance.</strong> This is the worst thing you can do. Even if you think the complaint has no merit, you must follow the process.</li>
                <li><strong>Being defensive.</strong> If the grievance is about your own decisions or management style, it is natural to feel defensive. But approaching the process with an open mind is essential.</li>
                <li><strong>Treating the employee differently afterwards.</strong> Any form of retaliation, whether deliberate or unconscious, can lead to a victimisation claim. Make sure the employee is not disadvantaged for having raised a grievance.</li>
                <li><strong>Taking too long.</strong> Grievances should be dealt with without unreasonable delay. Keep the employee updated on progress throughout.</li>
                <li><strong>Forgetting the appeal.</strong> Always offer the right to appeal in your outcome letter. Missing this step is a breach of the ACAS Code.</li>
            </ul>

            <p>Grievances can be difficult and emotionally charged, but they do not have to derail your business. By following a clear process and treating the employee fairly, you can resolve the issue and move forward with confidence.</p>

