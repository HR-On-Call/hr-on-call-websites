            <h2>Common Contract Mistakes</h2>

            <p>Having reviewed hundreds of employment contracts over the years, here are the mistakes we see most often:</p>

            <ul>
                <li><strong>Using a generic internet template:</strong> Free templates are rarely tailored to your business and often contain clauses that are unenforceable or irrelevant. Worse, they may be written for a different legal jurisdiction entirely.</li>
                <li><strong>Not updating contracts:</strong> Employment law changes regularly. If your contracts have not been reviewed in the last few years, they may not comply with current requirements, particularly the day-one statement rules introduced in April 2020.</li>
                <li><strong>Ambiguous wording around hours and pay:</strong> If your contracts are vague about working hours, overtime, or how bonuses are calculated, you are inviting disputes. Be as specific as possible.</li>
                <li><strong>Forgetting about existing employees:</strong> When you update your standard contract, remember that existing employees are still on their old terms. You cannot simply impose new terms unilaterally. Changes to existing contracts require consultation and agreement.</li>
                <li><strong>Missing probationary period details:</strong> Since 2020, you must include details of any probationary period in the day-one statement. If you operate a probationary period but do not mention it in the contract, you may find it difficult to rely on.</li>
                <li><strong>Overly aggressive restrictive covenants:</strong> Restrictions that are too broad or too long will simply be struck out by a court, leaving you with no protection at all. It is better to have reasonable restrictions that will actually be upheld.</li>
            </ul>

            <h2>When Should You Review Your Contracts?</h2>

            <p>We recommend reviewing your employment contracts at least once a year, and whenever there is a significant change in employment law. You should also review and potentially update contracts when:</p>

            <ul>
                <li>An employee's role changes significantly</li>
                <li>You introduce new benefits or change existing ones</li>
                <li>Your business structure changes</li>
                <li>You become aware of a gap or problem with your current template</li>
            </ul>

