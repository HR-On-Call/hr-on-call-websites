            <p>A well-drafted employment contract is one of the most important documents in your business. It sets the ground rules for the working relationship, protects your interests, and helps prevent misunderstandings down the line. Yet it is surprising how many employers either do not have written contracts at all or are using templates that do not cover the basics.</p>

            <p>In this guide, we will explain what the law requires you to include, what additional clauses you should consider, and the common mistakes that can leave you exposed.</p>

            <h2>The Legal Requirement: Written Statement of Terms</h2>

            <p>Since April 2020, every employee and worker is entitled to a written statement of employment particulars from day one of their employment. This is often referred to as a section 1 statement, after the relevant section of the Employment Rights Act 1996.</p>

            <p>This is a legal obligation, not a nice-to-have. If you do not provide one, an employment tribunal can award the employee two to four weeks' pay as compensation, and it weakens your position in any other claim they might bring.</p>

            <p>The written statement must include the following information, provided on or before the employee's first day:</p>

            <ol>
                <li>The employer's name and the employee's name</li>
                <li>The date employment began and the date on which continuous employment began (if different)</li>
                <li>The job title or a brief description of the work</li>
                <li>The place of work, or an indication that the employee will work in various locations</li>
                <li>Pay details, including how much, how often, and the method of payment</li>
                <li>Working hours, including whether they may be variable</li>
                <li>Holiday entitlement, including public holidays and holiday pay</li>
                <li>Details of any probationary period, including its length and conditions</li>
                <li>Any benefits provided by the employer, such as pension, health insurance, or company car</li>
                <li>Any training requirements, including whether the employee must pay for training if they leave</li>
            </ol>

            <p>Additional information must be provided within two months of the start date, covering matters such as sick pay, notice periods, pension arrangements, disciplinary and grievance procedures, and any collective agreements.</p>

            <p>In practice, most employers combine all of this into a single employment contract issued before or on the first day, which is the approach we recommend.</p>

            <h2>Essential Clauses Every Contract Should Have</h2>

            <p>Beyond the statutory minimum, there are several clauses that we strongly advise including in every employment contract:</p>

            <h3>Notice periods</h3>
            <p>You must specify the notice period required from both sides. The statutory minimum is one week for each year of service (up to 12 weeks), but many employers set a longer contractual notice period, particularly for senior roles. A three-month notice period for management positions is common and gives you time to plan for their departure and find a replacement.</p>

            <h3>Confidentiality</h3>
            <p>All employees have an implied duty of confidentiality, but relying on this alone is risky. An express confidentiality clause should define what constitutes confidential information in your business and make clear that the obligation continues after the employment ends.</p>

            <h3>Intellectual property</h3>
            <p>If employees create anything as part of their work, such as designs, software, written content, or inventions, you need a clause confirming that the intellectual property belongs to the business. Without this, ownership can become complicated.</p>

            <h3>Deductions from pay</h3>
            <p>If you want the ability to deduct specific amounts from an employee's pay, for example to recover overpayments or the cost of unreturned equipment, you need the employee's written consent. Including an appropriate clause in the contract provides this consent.</p>

            <h3>Lay-off and short-time working</h3>
            <p>If your business might need to reduce hours or temporarily lay off staff during quiet periods, you need a contractual right to do so. Without this clause, reducing someone's hours or pay without their agreement would be a breach of contract.</p>

            <h2>Restrictive Covenants: Protecting Your Business After They Leave</h2>

            <p>Restrictive covenants are clauses that limit what an employee can do after they leave your employment. The most common types are:</p>

            <ul>
                <li><strong>Non-compete:</strong> Prevents the employee from working for a competitor for a specified period</li>
                <li><strong>Non-solicitation:</strong> Prevents the employee from approaching your clients or customers</li>
                <li><strong>Non-dealing:</strong> Prevents the employee from doing business with your clients, even if the client approaches them</li>
                <li><strong>Non-poaching:</strong> Prevents the employee from recruiting your other staff</li>
            </ul>

            <p>Restrictive covenants are only enforceable if they go no further than is reasonably necessary to protect a legitimate business interest. This means the duration, geographical scope, and breadth of the restriction must all be proportionate. A six-month non-compete for a junior employee with no client contact is unlikely to be upheld by a court, whereas the same restriction for a sales director with key client relationships might be perfectly reasonable.</p>

