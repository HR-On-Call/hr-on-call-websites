            <p>You have completed your investigation, and the evidence suggests there is a case to answer. Now you need to hold a disciplinary hearing. For many business owners, this is one of the most stressful parts of managing people, especially if you have never done it before.</p>

            <p>The good news is that if you prepare properly and follow a clear process, you can get through a disciplinary hearing confidently and fairly. In this guide, we will take you through each stage, from preparation to the outcome letter.</p>

            <h2>Before the Hearing: Preparation Is Everything</h2>

            <p>A disciplinary hearing should never be rushed. Good preparation is the single biggest factor in whether the process stands up to scrutiny later. Here is what you need to do before the hearing takes place:</p>

            <ol>
                <li><strong>Appoint a hearing chair.</strong> This must be someone different from the person who carried out the <a href="/articles/how-to-conduct-a-workplace-investigation.php">workplace investigation</a>. In smaller businesses, this can be the business owner, provided they were not involved in the investigation.</li>
                <li><strong>Write the invitation letter.</strong> This should set out the allegations clearly, include copies of the evidence being relied upon (such as the investigation report, witness statements and relevant documents), state the date, time and location of the hearing, warn the employee of possible outcomes including dismissal if applicable, and remind them of their right to be accompanied.</li>
                <li><strong>Give adequate notice.</strong> There is no set minimum in law, but five working days is generally considered reasonable. The employee needs enough time to review the evidence and prepare their response.</li>
                <li><strong>Arrange a note-taker.</strong> Having someone present whose sole job is to take notes allows the chair to focus on listening and asking questions. These notes are important evidence if the matter goes further.</li>
                <li><strong>Review the evidence pack.</strong> The hearing chair should read all the investigation materials thoroughly before the day. You should not be seeing the evidence for the first time at the hearing.</li>
            </ol>

            <h2>Running the Hearing</h2>

            <p>On the day, the hearing should follow a structured format. This keeps things fair, focused and manageable. Here is a step-by-step approach:</p>

            <ol>
                <li><strong>Introductions and explanation.</strong> Open the hearing by confirming who is present, explaining the purpose of the meeting, and outlining how it will be conducted. Make clear that no decision has been made yet.</li>
                <li><strong>Present the management case.</strong> Summarise the allegations and the evidence gathered during the investigation. Refer to the investigation report and any supporting documents.</li>
                <li><strong>Allow the employee to respond.</strong> This is the most important part of the hearing. The employee must have a genuine opportunity to respond to each allegation, challenge any evidence, and put forward their own account or any mitigating factors.</li>
                <li><strong>Ask questions.</strong> The chair should ask questions to clarify anything that is unclear. Avoid leading or aggressive questioning. The aim is to understand the full picture.</li>
                <li><strong>Allow the companion to participate.</strong> The employee's companion (a trade union representative or work colleague) can address the hearing, confer with the employee, and sum up the employee's case. However, they cannot answer questions on the employee's behalf.</li>
                <li><strong>Adjourn to make a decision.</strong> Never deliver the outcome on the spot. Adjourn the hearing and take time to consider everything that has been said. This shows that the decision was properly considered, which matters if the case reaches a tribunal.</li>
            </ol>

            <p>If the employee raises new information during the hearing that requires further investigation, you should adjourn the hearing and carry out that additional investigation before reconvening.</p>

            <h2>Making the Decision</h2>

            <p>When deciding on the outcome, the hearing chair should consider the following:</p>

            <ul>
                <li>Does the evidence support the allegation on the balance of probabilities? You do not need to prove it beyond reasonable doubt, as this is not a criminal court.</li>
                <li>What explanation or mitigation has the employee offered?</li>
                <li>What is the employee's disciplinary record? Have they received previous warnings for similar issues?</li>
                <li>How have similar cases been dealt with in the past? Consistency matters.</li>
                <li>Is the proposed sanction reasonable and proportionate?</li>
            </ul>

            <p>The possible outcomes of a disciplinary hearing typically include no further action, a first written warning, a final written warning, or dismissal. In cases of <a href="/articles/gross-misconduct-what-counts-and-what-to-do.php">gross misconduct</a>, summary dismissal without notice may be appropriate.</p>

            <p>Whatever the decision, it must be proportionate. Dismissing someone for a first minor offence when a written warning would have been appropriate is exactly the kind of thing that leads to successful unfair dismissal claims.</p>

            <h2>The Outcome Letter</h2>

            <p>After the hearing, you must write to the employee confirming the outcome. This letter is a critical document, so take your time with it. As a minimum, the letter should include:</p>

            <ul>
                <li>A summary of the allegations considered</li>
                <li>The hearing chair's findings on each allegation</li>
                <li>The reasons for the decision</li>
                <li>The sanction being imposed, including any conditions or timescales (for example, a warning that will remain live for 12 months)</li>
                <li>The employee's right to appeal, including who to address the appeal to and the deadline for submitting it</li>
            </ul>

            <p>The <a href="/articles/acas-code-of-practice-what-employers-need-to-know.php">ACAS Code of Practice</a> requires you to inform the employee of the outcome in writing and to offer the right to appeal. Failing to include either of these is a common and avoidable mistake.</p>

            <h2>Tips for Getting It Right</h2>

            <p>Having chaired many disciplinary hearings for employers through HR On Call, here are the mistakes we see most often and how to avoid them:</p>

            <ul>
                <li><strong>Do not go in with a predetermined outcome.</strong> If the employee can show that the decision was made before the hearing even took place, the entire process is undermined.</li>
                <li><strong>Do not rush.</strong> Take proper adjournments if you need time to consider points raised during the hearing.</li>
                <li><strong>Do not ignore mitigation.</strong> Even if the allegation is upheld, the employee's personal circumstances, length of service, and any other relevant factors should be weighed in the decision.</li>
                <li><strong>Keep the process confidential.</strong> Only those who need to know should be involved.</li>
                <li><strong>Follow your own policy.</strong> If your staff handbook sets out a particular procedure, follow it. Departing from your own stated process is a common source of unfairness.</li>
            </ul>

