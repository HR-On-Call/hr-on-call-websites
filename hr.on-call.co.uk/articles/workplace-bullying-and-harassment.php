            <p>Bullying and harassment at work can cause serious harm to individuals and to your business. As an employer, you have a legal duty of care to protect your employees, and if you fail to take complaints seriously, you could find yourself facing employment tribunal claims, reputational damage, and the loss of good staff.</p>

            <p>In this guide, we will explain the difference between bullying and harassment, set out your legal obligations, and walk you through how to handle complaints effectively.</p>

            <h2>Understanding the Difference: Bullying vs Harassment</h2>

            <p>These terms are often used interchangeably, but they have different legal meanings, and the distinction matters.</p>

            <p><strong>Harassment</strong> has a specific legal definition under the Equality Act 2010. It is unwanted conduct related to a protected characteristic, such as age, sex, race, disability, religion, sexual orientation, gender reassignment, or pregnancy, that has the purpose or effect of violating someone's dignity or creating an intimidating, hostile, degrading, humiliating, or offensive environment. Harassment claims can be brought against the employer as well as the individual responsible.</p>

            <p><strong>Bullying</strong> does not have a specific legal definition in UK employment law. However, ACAS describes it as offensive, intimidating, malicious, or insulting behaviour that amounts to an abuse of power. While there is no standalone law against bullying, an employee who is bullied may still have legal options. They could resign and claim constructive unfair dismissal, bring a personal injury claim, or, if the bullying is related to a protected characteristic, bring a harassment claim.</p>

            <p>The practical takeaway is this: whether the complaint is labelled as bullying or harassment, you need to take it seriously and investigate it properly.</p>

            <h2>Your Legal Obligations as an Employer</h2>

            <p>You have several overlapping legal duties when it comes to bullying and harassment:</p>

            <ul>
                <li><strong>Duty of care:</strong> Under common law and health and safety legislation, you must take reasonable steps to protect employees from foreseeable harm, including psychological harm caused by bullying or harassment.</li>
                <li><strong>Vicarious liability:</strong> Under the Equality Act 2010, you can be held liable for harassment carried out by your employees during the course of their employment, unless you can show you took all reasonable steps to prevent it.</li>
                <li><strong>Third-party harassment:</strong> The Worker Protection (Amendment of Equality Act 2010) Act 2023 introduced a duty on employers to take reasonable steps to prevent sexual harassment of employees by third parties such as customers, clients, or suppliers.</li>
            </ul>

            <p>The key phrase in all of this is "reasonable steps." If you can demonstrate that you have taken genuine, proactive measures to prevent bullying and harassment, you will be in a much stronger position if a claim is made.</p>

            <h2>Step 1: Get Your Policy Right</h2>

            <p>Every employer should have a clear anti-bullying and harassment policy. This does not need to be a lengthy legal document. It should be straightforward and easy to understand, covering:</p>

            <ol>
                <li>What bullying and harassment are, with practical examples relevant to your workplace</li>
                <li>That bullying and harassment will not be tolerated and may result in disciplinary action up to and including dismissal</li>
                <li>How employees can raise a complaint, both formally and informally</li>
                <li>How complaints will be investigated</li>
                <li>That complainants will be protected from retaliation</li>
                <li>Where employees can get support, including any employee assistance programme you offer</li>
            </ol>

            <p>Make sure every employee has access to the policy and knows where to find it. If you need help putting one together, HR On Call's <a href="/documents.php">document service</a> can create a tailored policy for your business.</p>

            <h2>Step 2: Respond to Complaints Promptly</h2>

            <p>When an employee comes to you with a complaint about bullying or harassment, how you respond in the first few days sets the tone for everything that follows. Here is what you should do:</p>

            <ol>
                <li><strong>Listen and take it seriously:</strong> Even if the complaint seems minor to you, it clearly matters to the person raising it. Do not dismiss it or suggest they are being oversensitive.</li>
                <li><strong>Ask what outcome they want:</strong> Some employees want formal action. Others want the behaviour to stop without a formal process. Understanding their expectations helps you decide the best approach.</li>
                <li><strong>Consider whether informal resolution is appropriate:</strong> For less serious matters, a facilitated conversation or mediation may resolve things quickly. This is not always possible, but it is worth considering.</li>
                <li><strong>If formal action is needed, investigate:</strong> Appoint someone impartial to investigate the complaint. This person should not be involved in the situation or have a close relationship with either party.</li>
            </ol>

            <h2>Step 3: Conduct a Fair Investigation</h2>

            <p>A good investigation is thorough, impartial, and timely. Here is a practical framework:</p>

            <ol>
                <li><strong>Plan the investigation:</strong> Identify what you need to find out, who you need to speak to, and what documents or evidence you need to review.</li>
                <li><strong>Interview the complainant:</strong> Get a detailed account of what happened, when, where, and whether anyone else was present. Ask about the impact on them.</li>
                <li><strong>Interview the alleged perpetrator:</strong> Put the allegations to them clearly and give them a full opportunity to respond. They should be told the nature of the complaint but not necessarily every detail at this stage.</li>
                <li><strong>Interview witnesses:</strong> Speak to anyone who may have relevant information. Remind them that the matter is confidential.</li>
                <li><strong>Gather evidence:</strong> This might include emails, messages, CCTV footage, or relevant records.</li>
                <li><strong>Reach your findings:</strong> Weigh the evidence on the balance of probabilities. You do not need to prove anything beyond reasonable doubt.</li>
                <li><strong>Write an investigation report:</strong> Set out your findings clearly and recommend next steps, whether that is no further action, informal resolution, or formal disciplinary proceedings.</li>
            </ol>

            <p>If you do not have the internal resource or expertise to conduct the investigation yourself, bringing in an external investigator can be a wise investment. This is one of the areas where <a href="/workplace-issues.php#investigations">specialist workplace investigation support</a> makes a real difference.</p>

            <h2>Step 4: Take Action and Follow Up</h2>

            <p>Once the investigation is complete, you need to act on the findings. If the complaint is upheld, this may involve disciplinary action against the perpetrator, changes to working arrangements, or additional training. If the complaint is not upheld, you should still consider whether there are any steps you can take to improve the working relationship.</p>

            <p>Whatever the outcome, keep the complainant informed throughout the process. One of the most common complaints we hear from employees is not about the outcome itself, but about being left in the dark while the investigation was ongoing.</p>

            <p>After the matter is resolved, follow up with both parties after a few weeks to check that the situation has genuinely improved and that there has been no retaliation.</p>

            <h2>Prevention Is Always Better Than Cure</h2>

            <p>The best way to deal with bullying and harassment is to prevent it from happening in the first place. Here are the steps we recommend to every employer we work with:</p>

            <ul>
                <li><strong>Train your managers:</strong> Managers need to know how to spot the signs of bullying and harassment, and how to respond when they do. This does not require expensive courses. Even a short briefing session can make a significant difference.</li>
                <li><strong>Lead by example:</strong> The culture of your organisation starts at the top. If senior people treat others with respect, that sets the standard for everyone.</li>
                <li><strong>Make it easy to speak up:</strong> Employees are more likely to raise concerns early if they trust that they will be listened to and that there will be no negative consequences for speaking up.</li>
                <li><strong>Review regularly:</strong> Revisit your policy at least annually. Consider running an anonymous staff survey to check whether people feel safe and respected at work.</li>
            </ul>

