            <p>When an employee appeals a disciplinary or grievance outcome, it can feel like you are going back to square one. But appeals are not something to dread. They are actually an important safeguard, both for your employee and for your business. Getting the appeal process right can be the difference between resolving a situation fairly and ending up at an employment tribunal.</p>

            <p>In this guide, we will walk you through the key steps to handling appeals properly, so you can feel confident you are meeting your legal obligations and treating your people fairly.</p>

            <h2>Why Appeals Matter</h2>

            <p>The right to appeal is a fundamental part of any disciplinary or grievance process. The <a href="https://www.acas.org.uk/acas-code-of-practice-on-disciplinary-and-grievance-procedures" target="_blank" rel="noopener">ACAS Code of Practice on Disciplinary and Grievance Procedures</a> makes it clear that employees must be given the opportunity to appeal against any formal decision. If you skip this step or handle it poorly, a tribunal can increase any compensation award by up to 25%.</p>

            <p>Beyond the legal side, a well-run appeal process shows your team that you take fairness seriously. It can also catch genuine mistakes before they turn into costly disputes.</p>

            <h2>Step 1: Acknowledge the Appeal Promptly</h2>

            <p>When an employee submits a written appeal, you should acknowledge it in writing as soon as possible, ideally within two to three working days. Your acknowledgement should confirm:</p>

            <ul>
                <li>That you have received the appeal</li>
                <li>That you will arrange a hearing and confirm the date shortly</li>
                <li>Their right to be accompanied at the hearing by a trade union representative or a work colleague</li>
            </ul>

            <p>There is no strict legal deadline for holding the appeal hearing, but the ACAS Code says it should be arranged without unreasonable delay. We generally recommend holding it within five to ten working days of receiving the appeal.</p>

            <h2>Step 2: Choose the Right Person to Hear the Appeal</h2>

            <p>This is one of the most common mistakes we see employers make. The person who hears the appeal must not be the same person who made the original decision. Ideally, the appeal manager should be more senior than the original decision-maker, but we understand that in smaller businesses this is not always possible.</p>

            <p>If you are a small business and there is genuinely nobody else available internally, you may need to consider bringing in an external party. This is one of the areas where <a href="/pay-as-you-go.php">pay-as-you-go HR support</a> can be invaluable, giving you access to an impartial person to chair the hearing.</p>

            <h3>What if the business owner made the original decision?</h3>

            <p>If you are the owner and you conducted the original hearing, you will need someone else to handle the appeal. This could be a fellow director, a senior manager, or an external HR professional. At HR On Call, we regularly chair appeal hearings for clients in exactly this situation.</p>

            <h2>Step 3: Prepare Thoroughly for the Hearing</h2>

            <p>Before the hearing, make sure the appeal manager has access to all relevant documentation, including:</p>

            <ol>
                <li>The original investigation notes and evidence</li>
                <li>The outcome letter from the disciplinary or grievance hearing</li>
                <li>The employee's written appeal, including their stated grounds for appealing</li>
                <li>Any new evidence the employee has indicated they wish to present</li>
                <li>Your company's disciplinary or grievance policy</li>
            </ol>

            <p>Send the employee a letter confirming the date, time, and location of the hearing at least five working days in advance. Include copies of any documents that will be referred to, and remind them of their right to be accompanied.</p>

            <h2>Step 4: Conduct the Appeal Hearing Fairly</h2>

            <p>The appeal hearing should be conducted in a private, quiet space where you will not be interrupted. Begin by explaining the purpose of the hearing and how it will be structured.</p>

            <p>There are broadly two approaches to an appeal:</p>

            <ul>
                <li><strong>A review of the original decision:</strong> The appeal manager looks at whether the original process was fair and the decision was reasonable, based on the evidence available at the time.</li>
                <li><strong>A full rehearing:</strong> The appeal manager hears the case again from scratch, considering all evidence including anything new.</li>
            </ul>

            <p>Which approach you take will depend on the grounds of the appeal and what your policy says. If the employee is arguing that the process was flawed or the sanction was too harsh, a review may be sufficient. If there is significant new evidence, a rehearing is often more appropriate.</p>

            <p>During the hearing, give the employee a full opportunity to explain their grounds for appeal. Listen carefully, ask questions to clarify any points, and take detailed notes. If a companion is present, they can present the case on the employee's behalf, but the employee should answer direct questions themselves.</p>

            <h2>Step 5: Make and Communicate Your Decision</h2>

            <p>After the hearing, take time to consider your decision carefully. You do not need to give your answer on the spot, and we would generally advise against doing so. Take at least a day to review your notes and the evidence before reaching your conclusion.</p>

            <p>The possible outcomes are:</p>

            <ol>
                <li><strong>Uphold the original decision:</strong> You agree with the outcome and the process was fair.</li>
                <li><strong>Overturn the decision:</strong> You find that the original decision was wrong or unfair.</li>
                <li><strong>Substitute a different outcome:</strong> For example, replacing a dismissal with a final written warning.</li>
            </ol>

            <p>Communicate your decision in writing as soon as possible, normally within five working days of the hearing. Your letter should clearly explain the reasons for your decision. In most cases, the appeal decision is final, and your letter should confirm this.</p>

            <h2>Common Pitfalls to Avoid</h2>

            <p>Over the years, we have seen a number of recurring mistakes that employers make with appeals. Here are the ones to watch out for:</p>

            <ul>
                <li><strong>Using the same decision-maker:</strong> As mentioned, this undermines the entire process.</li>
                <li><strong>Treating the appeal as a rubber stamp:</strong> The appeal manager must genuinely consider whether the original decision was fair and reasonable.</li>
                <li><strong>Ignoring new evidence:</strong> If the employee presents new information, it must be properly considered.</li>
                <li><strong>Taking too long:</strong> Unreasonable delays can be held against you at tribunal.</li>
                <li><strong>Not keeping records:</strong> Detailed notes of the hearing are essential. Consider having a separate note-taker present.</li>
            </ul>

