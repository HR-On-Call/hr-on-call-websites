            <p>Dismissing an employee is one of the hardest decisions a business owner can make. It is stressful, it feels personal, and the fear of getting it wrong can lead to paralysis. We regularly speak to employers who have put up with serious performance or conduct issues for months, sometimes years, because they are afraid of the legal consequences of letting someone go.</p>

            <p>The reality is that you absolutely can dismiss an employee, provided you have a fair reason and you follow the correct process. In this guide, we will explain exactly what that means in practice.</p>

            <h2>The Two Tests for Fair Dismissal</h2>

            <p>For a dismissal to be fair under UK employment law, two conditions must be met. First, you must have a fair reason for the dismissal. Second, you must follow a fair procedure. Getting one right but not the other is not enough. An employer who has an excellent reason for dismissal but skips the procedure can still lose an unfair dismissal claim, and vice versa.</p>

            <p>It is worth noting that employees generally need two years of continuous service to bring an unfair dismissal claim. However, there are exceptions. Dismissals connected to discrimination, whistleblowing, pregnancy, or asserting a statutory right can be challenged regardless of length of service. So following a fair process is always advisable, even for newer employees.</p>

            <h2>The Five Fair Reasons for Dismissal</h2>

            <p>UK employment law recognises five potentially fair reasons for dismissal:</p>

            <ol>
                <li><strong>Conduct.</strong> This covers situations where the employee has behaved in a way that breaches your rules or standards. It ranges from persistent minor issues such as repeated lateness to serious matters such as <a href="/articles/gross-misconduct-what-counts-and-what-to-do.php">gross misconduct</a>. For misconduct dismissals, you should follow a full disciplinary process in line with the <a href="/articles/acas-code-of-practice-what-employers-need-to-know.php">ACAS Code of Practice</a>.</li>
                <li><strong>Capability.</strong> This applies when the employee is unable to do the job to the required standard. It includes both performance-related capability, where the employee is not meeting targets or standards despite support, and health-related capability, where a long-term illness or condition means they can no longer fulfil their role. Capability dismissals require a process that demonstrates you gave the employee a reasonable opportunity to improve.</li>
                <li><strong>Redundancy.</strong> If the business needs fewer employees to do a particular kind of work, dismissal by reason of redundancy can be fair. However, there is a specific consultation process to follow, and selection must be based on objective criteria.</li>
                <li><strong>Breach of a statutory restriction.</strong> This applies where continuing to employ someone would break the law. For example, if an employee whose role requires driving loses their driving licence, or if an employee loses the right to work in the UK.</li>
                <li><strong>Some other substantial reason (SOSR).</strong> This is a catch-all category that covers situations not fitting neatly into the other four. Examples include a breakdown in trust and confidence, a refusal to accept reasonable changes to terms and conditions, or pressure from a client to remove an employee. SOSR dismissals must still be handled fairly and reasonably.</li>
            </ol>

            <h2>The Fair Procedure: Step by Step</h2>

            <p>Having a fair reason is only half the picture. You also need to follow a fair process. While the exact steps vary depending on the reason for dismissal, the core principles are the same. Here is a general framework that applies to most situations:</p>

            <ol>
                <li><strong>Investigate.</strong> Before taking any formal action, carry out a <a href="/articles/how-to-conduct-a-workplace-investigation.php">reasonable investigation</a> to establish the facts. This does not need to be a police-level inquiry, but it does need to be thorough enough that a reasonable employer would consider it adequate.</li>
                <li><strong>Notify the employee.</strong> Write to the employee setting out the concerns and inviting them to a formal meeting. Provide copies of any evidence and give them enough time to prepare.</li>
                <li><strong>Hold a formal meeting.</strong> At the <a href="/articles/how-to-handle-a-disciplinary-hearing.php">hearing</a>, present the management case and give the employee a full opportunity to respond. Allow them to be accompanied by a trade union representative or work colleague.</li>
                <li><strong>Consider the response.</strong> Adjourn to consider everything before making a decision. Take into account any mitigating factors the employee has raised, their length of service, their disciplinary record, and how similar cases have been handled previously.</li>
                <li><strong>Communicate the decision.</strong> If you decide to dismiss, confirm this in writing. The letter should explain the reason for dismissal, the effective date, any notice period or payment in lieu of notice, and the right to appeal.</li>
                <li><strong>Offer an appeal.</strong> The employee must have the opportunity to appeal the decision. The appeal should be heard by someone more senior or someone who has not been involved in the process. This is a requirement of the ACAS Code.</li>
            </ol>

            <h2>Notice Periods and Final Pay</h2>

            <p>Unless the dismissal is for gross misconduct, the employee is entitled to their contractual or statutory notice period, whichever is longer. Statutory minimum notice is one week for each complete year of service, up to a maximum of 12 weeks.</p>

            <p>You can choose to have the employee work their notice, or you can make a payment in lieu of notice. Either approach is acceptable, provided the contract allows for payment in lieu.</p>

            <p>The employee's final pay should include their salary up to the termination date, any payment in lieu of notice, accrued but untaken holiday pay, and any other contractual entitlements such as outstanding expenses or commission. Having clear <a href="/documents.php">employment contracts</a> that set out these terms makes the final pay calculation much simpler.</p>

            <h2>How to Protect Your Business</h2>

            <p>Here are the practical steps we recommend to every employer we work with at HR On Call:</p>

            <ul>
                <li><strong>Document everything from day one.</strong> Keep records of any informal conversations, performance reviews, and written warnings. If you ever need to dismiss someone, this paper trail is invaluable.</li>
                <li><strong>Follow your own policies.</strong> If your staff handbook sets out a specific process, follow it. Tribunals will hold you to your own stated procedures.</li>
                <li><strong>Be consistent.</strong> If you dismissed one employee for persistent lateness but gave another employee in the same situation a final warning, you will need a good explanation for the difference.</li>
                <li><strong>Do not delay.</strong> If there is a performance or conduct issue, address it early. Putting it off usually makes the situation worse and can undermine your case if you later need to dismiss.</li>
                <li><strong>Consider alternatives.</strong> Before dismissing, think about whether there are other options. Could the employee be moved to a different role? Could additional training help? Could the issue be resolved through a managed exit? Showing that you considered alternatives before reaching the decision to dismiss is important.</li>
                <li><strong>Get advice.</strong> If you have never dismissed anyone before, or if the situation is complicated, getting professional support is an investment that almost always pays for itself.</li>
            </ul>

            <p>Dismissing an employee does not have to be a nightmare. With the right reason and the right process, you can manage the situation with confidence, treat the employee fairly, and protect your business from claims.</p>

